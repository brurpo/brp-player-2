#[cfg(test)]
mod tests {
    use super::Lang;
    use crate::ai::AiKind;
    use crate::effects::param_options;

    /// Every AI parameter is translated, with as many choices as in English.
    #[test]
    fn ai_params_translated() {
        for k in AiKind::ALL {
            for p in &k.file().params {
                let (label, desc) = Lang::Pt.ai_param(k.id(), &p.name).unwrap_or_else(|| panic!("{} {} not translated", k.id(), p.name));
                assert!(!label.is_empty());
                let (en, pt) = (param_options(&p.desc).map(|o| o.len()), param_options(desc).map(|o| o.len()));
                assert_eq!(en, pt, "{} {}: choices", k.id(), p.name);
            }
        }
    }
}
